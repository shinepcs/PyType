create or replace function public.get_my_rank(
  p_session_id uuid,
  p_content_version text
)
returns table (
  rank bigint,
  player_name text,
  score integer,
  accuracy numeric(5, 2),
  wpm numeric(6, 2),
  problems_solved smallint,
  best_combo smallint,
  survival_ms integer,
  created_at timestamptz
)
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  if auth.uid() is null then
    raise exception 'authentication required' using errcode = '42501';
  end if;
  if p_session_id is null then
    raise exception 'session id is required' using errcode = '22023';
  end if;
  if p_content_version is null
     or p_content_version !~ '^[A-Za-z0-9][A-Za-z0-9._-]{0,19}$' then
    raise exception 'invalid content version' using errcode = '22023';
  end if;

  return query
  with target as (
    select entry.*
    from public.ranking_entries as entry
    where entry.user_id = auth.uid()
      and entry.session_id = p_session_id
      and entry.content_version = p_content_version
      and entry.game_mode = 'quick'
    limit 1
  ),
  other_user_runs as (
    select
      entry.*,
      row_number() over (
        partition by entry.user_id
        order by
          entry.score desc,
          entry.accuracy desc,
          entry.problems_solved desc,
          entry.best_combo desc,
          entry.wpm desc,
          entry.created_at asc,
          entry.id asc
      ) as user_position
    from public.ranking_entries as entry
    where entry.user_id <> auth.uid()
      and entry.content_version = p_content_version
      and entry.game_mode = 'quick'
  ),
  candidates as (
    select
      other.id,
      other.player_name,
      other.score,
      other.accuracy,
      other.wpm,
      other.problems_solved,
      other.best_combo,
      other.survival_ms,
      other.created_at,
      false as is_target
    from other_user_runs as other
    where other.user_position = 1
    union all
    select
      target.id,
      target.player_name,
      target.score,
      target.accuracy,
      target.wpm,
      target.problems_solved,
      target.best_combo,
      target.survival_ms,
      target.created_at,
      true as is_target
    from target
  ),
  ranked as (
    select
      row_number() over (
        order by
          candidate.score desc,
          candidate.accuracy desc,
          candidate.problems_solved desc,
          candidate.best_combo desc,
          candidate.wpm desc,
          candidate.created_at asc,
          candidate.id asc
      ) as entry_rank,
      candidate.*
    from candidates as candidate
  )
  select
    ranked.entry_rank,
    ranked.player_name,
    ranked.score,
    ranked.accuracy,
    ranked.wpm,
    ranked.problems_solved,
    ranked.best_combo,
    ranked.survival_ms,
    ranked.created_at
  from ranked
  where ranked.is_target;
end;
$$;

