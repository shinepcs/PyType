grant insert (
  user_id,
  session_id,
  player_name,
  score,
  accuracy,
  wpm,
  problems_solved,
  best_combo,
  survival_ms,
  game_mode,
  content_version,
  client_version
) on public.ranking_entries to authenticated;

-- created_at and id are intentionally omitted from the INSERT grant. They can
-- only be assigned by PostgreSQL, not backdated or chosen by a browser client.
revoke all on sequence public.ranking_entries_id_seq from public, anon, authenticated;
grant usage on sequence public.ranking_entries_id_seq to authenticated;

