create or replace function public.submit_shared_question(
  p_content_version text,
  p_question jsonb,
  p_question_id text default null
)
returns table (question_id text, revision_id bigint)
language plpgsql
security definer
set search_path = ''
as $$
declare
  new_question_id text;
  new_revision_id bigint;
  level_value integer;
  code_value text;
  answer_value text;
begin
  if auth.uid() is null then
    raise exception 'authentication required' using errcode = '42501';
  end if;
  if p_content_version is null
     or p_content_version !~ '^[A-Za-z0-9][A-Za-z0-9._-]{0,19}$' then
    raise exception 'invalid content version' using errcode = '22023';
  end if;
  if p_question is null or jsonb_typeof(p_question) <> 'object'
     or p_question - array['level','type','skill','difficulty','code','output','outputMode',
       'answer','acceptedAnswers','targetSeconds','tags'] <> '{}'::jsonb then
    raise exception 'invalid question shape' using errcode = '22023';
  end if;
  if jsonb_typeof(p_question->'acceptedAnswers') <> 'array'
     or jsonb_array_length(p_question->'acceptedAnswers') > 5
     or jsonb_typeof(p_question->'tags') <> 'array'
     or jsonb_array_length(p_question->'tags') > 8 then
    raise exception 'invalid question arrays' using errcode = '22023';
  end if;
  if jsonb_typeof(p_question->'level') <> 'number'
     or jsonb_typeof(p_question->'difficulty') <> 'number'
     or jsonb_typeof(p_question->'targetSeconds') <> 'number'
     or jsonb_typeof(p_question->'type') <> 'string'
     or jsonb_typeof(p_question->'skill') <> 'string'
     or jsonb_typeof(p_question->'code') <> 'string'
     or jsonb_typeof(p_question->'output') <> 'string'
     or jsonb_typeof(p_question->'outputMode') <> 'string'
     or jsonb_typeof(p_question->'answer') <> 'string'
     or exists (
       select 1 from jsonb_array_elements(p_question->'acceptedAnswers') as item
       where jsonb_typeof(item) <> 'string' or char_length(item #>> '{}') not between 1 and 100
     )
     or exists (
       select 1 from jsonb_array_elements(p_question->'tags') as item
       where jsonb_typeof(item) <> 'string' or (item #>> '{}') !~ '^[a-z][a-z0-9-]*$'
     ) then
    raise exception 'invalid question field types' using errcode = '22023';
  end if;

  level_value := (p_question->>'level')::integer;
  code_value := p_question->>'code';
  answer_value := p_question->>'answer';
  if level_value not in (1, 2)
     or (level_value = 1 and p_question->>'type' <> 'copy')
     or (level_value = 2 and p_question->>'type' <> 'fill')
     or p_question->>'skill' not in ('print','variable','assignment','number','string','boolean',
       'arithmetic','comparison','if','elif','else','for','range','while','break','continue',
       'list','append','pop','sort','reverse','len','sum','min','max','random','shuffle')
     or (p_question->>'difficulty')::integer not between 1 and 3
     or (p_question->>'targetSeconds')::integer not between 5 and 15
     or p_question->>'outputMode' not in ('exact', 'example')
     or code_value is null or char_length(code_value) not between 1 and 300
     or answer_value is null
     or char_length(answer_value) not between 1 and (case when level_value = 2 then 30 else 100 end)
     or code_value ~ E'[\\r\\t]' or answer_value ~ E'[\\r\\n\\t]'
     or code_value ~ E'[ ]+(\\n|$)'
     or char_length(coalesce(p_question->>'output', '')) > 200
     or coalesce(p_question->>'output', '') ~ E'[\\r\\t]'
     or coalesce(p_question->>'output', '') ~ E'[ ]+(\\n|$)' then
    raise exception 'question values out of range' using errcode = '22023';
  end if;
  if (level_value = 1 and (answer_value <> code_value or coalesce(p_question->>'output', '') <> ''))
     or not ((p_question->'acceptedAnswers') ? answer_value)
     or (level_value = 1 and (
       jsonb_array_length(p_question->'acceptedAnswers') <> 1
       or p_question->'acceptedAnswers'->>0 <> answer_value
     ))
     or (level_value = 2 and (
       (char_length(code_value) - char_length(replace(code_value, '_____', ''))) / 5 <> 1
       or coalesce(p_question->>'output', '') = ''
     )) then
    raise exception 'level contract mismatch' using errcode = '22023';
  end if;
  if exists (
    select 1 from public.shared_question_revisions as recent
    where recent.author_user_id = auth.uid() and recent.created_at > now() - interval '5 seconds'
  ) then
    raise exception 'please wait before another edit' using errcode = '55000';
  end if;
  if p_question_id is not null and p_question_id !~ '^[a-z][a-z0-9]*(?:[.-][a-z0-9]+)*$' then
    raise exception 'invalid question id' using errcode = '22023';
  end if;
  if p_question_id is null and (
    select count(distinct revision.question_id)
    from public.shared_question_revisions as revision
    where revision.content_version = p_content_version
  ) >= 500 then
    raise exception 'shared question limit reached' using errcode = '54000';
  end if;

  new_question_id := coalesce(p_question_id, 'community.' || gen_random_uuid()::text);
  insert into public.shared_question_revisions
    (question_id, author_user_id, content_version, question)
  values (new_question_id, auth.uid(), p_content_version, p_question)
  returning id into new_revision_id;
  return query select new_question_id, new_revision_id;
end;
$$;

