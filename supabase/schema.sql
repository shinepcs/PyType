create or replace function public.get_online_players(
  p_content_version text,
  p_limit integer default 50
)
returns table (player_name text, best_score integer)
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  if p_limit is null or p_limit < 1 or p_limit > 50 then
    raise exception 'limit must be between 1 and 50' using errcode = '22023';
  end if;
  if p_content_version is null
     or p_content_version !~ '^[A-Za-z0-9][A-Za-z0-9._-]{0,19}$' then
    raise exception 'invalid content version' using errcode = '22023';
  end if;
  return query
  select online.player_name, coalesce(max(entry.score), 0)::integer
  from public.online_players as online
  left join public.ranking_entries as entry
    on entry.user_id = online.user_id
    and entry.content_version = p_content_version and entry.game_mode = 'quick'
  where online.last_seen_at >= now() - interval '90 seconds'
  group by online.user_id, online.player_name, online.last_seen_at
  order by coalesce(max(entry.score), 0) desc, online.last_seen_at desc
  limit p_limit;
end;
$$;

