  question_id text,
  level smallint,
  type text,
  skill text,
  difficulty smallint,
  code text,
  output text,
  output_mode text,
  answer text,
  accepted_answers jsonb,
  target_seconds smallint,
  tags jsonb,
  revision_id bigint
)
